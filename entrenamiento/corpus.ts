/**
 * Con qué aprende el modelo.
 *
 * Frases escritas a mano, agrupadas por lo que la persona quiere saber. El
 * entrenador las multiplica después: las pasa a tercera persona ("te riego" →
 * "la riego"), les pone prefijos ("oye", "dime"), colas ("porfa") y erratas.
 * Así que aquí lo que hace falta es variedad de VOCABULARIO, no cantidad.
 *
 * Esa lección salió de medir. La primera versión tenía frases bonitas pero
 * pocas palabras distintas, y el modelo fallaba en "está marchita" — no porque
 * no entendiera la forma, sino porque "marchita" no aparecía en ningún lado.
 * Sin esa palabra sólo le quedaba el armazón ("está…"), que también usa clima
 * en "está nublado", y se iba por ahí. Por eso ahora cada clase trae sus
 * palabras propias, no sólo sus frases propias.
 *
 * Ninguna de estas frases está en `prueba.ts`, y esa separación es la única
 * razón por la que la cifra de aciertos significa algo.
 *
 * Hay colisiones a propósito. "le pongo agua a la maceta" es riego aunque diga
 * "maceta"; "la tierra está empapada" es sustrato aunque diga agua; "le pega el
 * sol" es luz aunque el sol también salga en clima. Sin esos casos el modelo
 * aprende que una palabra decide, y no es así.
 */

