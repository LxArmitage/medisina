const POR_ID = new Map(ESPECIES.map((especie) => [especie.id, especie]));

export function buscarEspecie(id: string): Especie | undefined {
  return POR_ID.get(id);
}

/**
 * Las "especies" genéricas: una por tipo de planta, para cuidar la que no está
 * en el catálogo. Nunca las propone el reconocimiento; las elige la persona.
 */
export function esGenerica(id: string): boolean {
  return id.startsWith('generica-');
}

export function especiesGenericas(): Especie[] {
  return ESPECIES.filter((e) => esGenerica(e.id));
}

/** Las que sí son especies de verdad (las que el modelo sabe reconocer). */
export function especiesReales(): Especie[] {
  return ESPECIES.filter((e) => !esGenerica(e.id));
}

/**
 * La genérica más parecida a una especie: si el modelo dudó entre dos
 * suculentas, lo más probable es que sea una suculenta, aunque no sea ninguna
 * de las dos.
 */
export function genericaParecida(especie: Especie): Especie | undefined {
  const id =
    especie.familiaFuncional === 'cactacea_suculenta'
      ? 'generica-suculenta'
      : especie.familiaFuncional === 'arborea' || (especie.familiaFuncional === 'arbustiva' && especie.bandasToleradas[0] === 'sol_pleno')
        ? 'generica-arbusto'
        : especie.bandasToleradas[0].startsWith('interior') || especie.bandasToleradas[0] === 'sombra'
          ? 'generica-interior'
          : especie.perfilHidrico === 'alto' && especie.familiaFuncional === 'herbacea'
            ? 'generica-huerto'
            : 'generica-flor';
  return buscarEspecie(id);
}

/** Búsqueda por texto sobre nombre común y científico, sin acentos. */
export function filtrarEspecies(consulta: string): Especie[] {
  const termino = normalizar(consulta.trim());
  if (!termino) return ESPECIES;
  return ESPECIES.filter((especie) => {
    const campos = [especie.nombreCientifico, ...especie.nombresComunes, ...(especie.nombresIngles ?? [])];
    return campos.some((campo) => normalizar(campo).includes(termino));
  });
}

function normalizar(texto: string): string {
  return texto
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
}
